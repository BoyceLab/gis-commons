"""Generate docs/maps/videos.md from data/videos.yml.  Run from the repository root: python3 scripts/generate.py"""
import html
from collections import OrderedDict
import yaml

esc = html.escape
d = yaml.safe_load(open("data/videos.yml", encoding="utf-8"))
ch = d["channel"]
out = ["<!-- Generated by scripts/generate.py from data/videos.yml. Edit the data file and run the script again. -->\n\n",
       "# Video gallery\n\n",
       f"Every public video on the [ALS Geospatial Hub YouTube channel]({ch['url']}), the channel GeoALS uses for map demonstrations, webinars and advocacy walk-throughs. "
       "Each card has a description and links to the maps shown, and selecting a card plays the video on this page. "
       "The list was read from the channel on 12 November 2026, and a scheduled workflow in the repository adds new uploads.\n\n",
       '<p><a href="#care">Care</a> · <a href="#research">Research</a> · <a href="#advocacy">Advocacy</a> · <a href="#stories">Stories</a> · <a href="#all-uploads">All uploads in one player</a> · <a href="#related-videos-on-other-channels">Related videos on other channels</a></p>\n\n']
intro = {"Care": "Clinic locator and clinic review tools.",
         "Research": "Webinars and presentations about the maps and the analyses behind them.",
         "Advocacy": "Walk-throughs of the legislative maps.",
         "Stories": "News coverage, GIS Day messages and story map tours."}
themes = OrderedDict((t, []) for t in intro)
for v in d["videos"]:
    themes.setdefault(v["theme"], []).append(v)
for t, vs in themes.items():
    if not vs:
        continue
    out.append(f"## {t}\n\n{intro.get(t, '')}\n\n<div class=\"videos\" markdown=\"0\">\n")
    for v in vs:
        links = "".join(f' <a href="{esc(l["url"])}">{esc(l["label"])}</a>.' for l in v.get("links") or [])
        out.append(
            f'<article class="video" id="v-{esc(v["id"])}"><div class="frame">'
            f'<img loading="lazy" alt="" src="https://i.ytimg.com/vi/{esc(v["id"])}/hqdefault.jpg">'
            f'<button type="button" data-id="{esc(v["id"])}" data-title="{esc(v["title"])}" aria-label="Play video: {esc(v["title"])}"><span>Play video</span></button></div>'
            f'<div class="body"><h3>{esc(v["title"])}</h3><p class="meta">Published {v["published"]} · <a href="https://www.youtube.com/watch?v={esc(v["id"])}">Watch on YouTube</a></p>'
            f'<p>{esc(v["description"])}{links}</p></div></article>\n')
    out.append("</div>\n\n[Back to top](#video-gallery)\n\n")
out.append("## All uploads\n\nThis player loads the channel's uploads playlist from YouTube, so it includes any video published after the cards above were last updated.\n\n"
           f'<div class="embed" markdown="0"><iframe loading="lazy" title="ALS Geospatial Hub uploads playlist" src="https://www.youtube-nocookie.com/embed/videoseries?list={ch["uploads_playlist"]}" allow="accelerometer; encrypted-media; gyroscope; picture-in-picture; web-share" allowfullscreen></iframe></div>\n\n')
out.append("## Related videos on other channels\n\n")
for e in d.get("elsewhere", []):
    out.append(f'- [{e["title"]}]({e["url"]}). {e["note"]}\n')
out.append(f"\n[Back to top](#video-gallery)\n\n## Sources\n\n- [ALS Geospatial Hub YouTube channel]({ch['url']}), read 12 November 2026\n- [GeoALS](https://www.geoals.org/)\n")
open("docs/maps/videos.md", "w", encoding="utf-8").write("".join(out))
print("videos:", len(d["videos"]))
